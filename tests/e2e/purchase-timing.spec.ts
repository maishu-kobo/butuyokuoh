import {expect,test} from '@playwright/test';

for(const width of [320,390,1440]) {
  test(`unified purchase timing saves through list and budget at ${width}px`,async({page},info)=>{
    await page.setViewportSize({width,height:900});
    await page.clock.setFixedTime(new Date('2026-11-26T03:00:00Z'));
    expect((await page.request.post('/api/auth/register',{data:{email:`timing-${crypto.randomUUID()}@example.test`,password:'test-password'}})).ok()).toBeTruthy();
    const origin={Origin:'http://localhost:3107'};
    const saved=await page.request.post('/api/items',{headers:origin,data:{manual:true,name:'小さな読書灯',price:3200,priority:4,image_url:'/demo/wishlist.svg',planned_purchase_date:'2027-02-15'}});
    expect(saved.ok()).toBeTruthy();const item=await saved.json();
    expect((await page.request.post('/api/items/ranking',{headers:origin,data:{action:'guide',itemId:item.id,priority:4,month:'2026-12',timing:'by',condition:'値下がりしたら'}})).ok()).toBeTruthy();
    const read=async()=>{const rows=await(await page.request.get('/api/items?with=buy-guide')).json();return rows.find((x:{id:number})=>x.id===item.id);};
    const initial=await read();
    await page.goto('/design');
    const guide=page.getByRole('button',{name:'小さな読書灯の優先度・購入時期を編集',exact:true});
    await expect(guide).toContainText('2027年2月15日');
    await expect(guide).not.toContainText('12月まで');
    await guide.click();
    const editor=page.getByRole('dialog',{name:'優先度と購入時期',exact:true});
    await expect(editor.getByRole('radio',{name:'日付',exact:true})).toBeChecked();
    await editor.getByRole('radio',{name:'月',exact:true}).check();
    await editor.getByRole('textbox',{name:'購入する年'}).fill('2027');
    await editor.getByRole('combobox',{name:'購入する月'}).selectOption('03');
    await editor.getByRole('combobox',{name:'時期の表し方'}).selectOption('around');
    await expect(editor.getByRole('button',{name:'保存',exact:true})).toBeInViewport();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
    await page.screenshot({path:info.outputPath(`timing-editor-${width}.png`)});
    await editor.getByRole('button',{name:'保存',exact:true}).click();
    await expect(editor).toHaveCount(0);await expect(guide).toContainText('2027年3月ごろ');
    expect(await read()).toMatchObject({priority:4,sort_order:initial.sort_order,planned_purchase_date:null,buy_guide:{month:'2027-03',timing:'around',condition:'値下がりしたら'}});
    await page.reload();await expect(guide).toContainText('2027年3月ごろ');
    await page.getByRole('link',{name:'出費予定',exact:true}).click();
    const month=page.getByRole('region',{name:'2027年3月',exact:true});
    await expect(month.getByRole('button',{name:'小さな読書灯の購入時期を変更',exact:true})).toContainText('目安');
    await expect(page.getByTestId('spend-selected-total')).toHaveText('¥3,200');
    await page.getByRole('checkbox',{name:'2027年3月の商品を全選択',exact:true}).click();
    await expect(page.getByTestId('spend-selected-total')).toHaveText('¥0');
    await month.getByRole('button',{name:'小さな読書灯の購入時期を変更',exact:true}).click();
    const timing=page.getByRole('dialog',{name:'購入時期',exact:true});
    await timing.getByRole('combobox',{name:'時期の表し方'}).selectOption('by');
    await timing.getByRole('button',{name:'保存',exact:true}).click();
    await expect(timing).toHaveCount(0);await expect(month.getByRole('button',{name:'小さな読書灯の購入時期を変更'})).toContainText('期限');
    await expect(page.getByTestId('spend-selected-total')).toHaveText('¥0');
    await page.getByRole('checkbox',{name:'表示中の商品を全選択',exact:true}).click();
    await page.screenshot({path:info.outputPath(`timing-budget-${width}.png`)});
    await month.getByRole('button',{name:'小さな読書灯の購入時期を変更'}).click();
    await timing.getByRole('radio',{name:'日付',exact:true}).check();
    await timing.getByLabel('購入する日',{exact:true}).fill('2027-04-05');
    await timing.getByRole('button',{name:'保存',exact:true}).click();
    await expect(timing).toHaveCount(0);
    await expect(page.getByRole('region',{name:'2027年4月',exact:true})).toBeVisible();
    expect(await read()).toMatchObject({planned_purchase_date:'2027-04-05',priority:4,sort_order:initial.sort_order,buy_guide:{month:'2027-03',timing:'by',condition:'値下がりしたら'}});
    await page.getByRole('switch',{name:'新しい表示を使う'}).click();
    await expect(page).toHaveURL(url=>url.pathname==='/');
    await expect(page.getByText('小さな読書灯',{exact:true})).toBeVisible();
    await page.getByRole('switch',{name:'新しい表示を使う'}).click();
    await page.getByRole('button',{name:'小さな読書灯の購入時期を変更',exact:true}).click();
    await timing.getByRole('radio',{name:'未定',exact:true}).check();
    await timing.getByRole('button',{name:'保存',exact:true}).click();
    await expect(timing).toHaveCount(0);
    await expect(page.getByRole('region',{name:'時期未定',exact:true})).toBeVisible();
    expect(await read()).toMatchObject({planned_purchase_date:null,buy_guide:{month:'',condition:'値下がりしたら'}});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  });
}
